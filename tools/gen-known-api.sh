#!/usr/bin/env bash
# Regenerates src/CardCrafter.Core/Validation/KnownApi.txt from a ygopro-core and ygopro-scripts checkout.
# Usage: tools/gen-known-api.sh <ygopro-core dir> <ygopro-scripts dir>
set -euo pipefail
core="$1"; scripts="$2"
out="$(dirname "$0")/../src/CardCrafter.Core/Validation/KnownApi.txt"
{
  echo "# Engine names known to YGO Card Crafter's script checker."
  echo "# Generated by tools/gen-known-api.sh from ygopro-core and ygopro-scripts. Do not edit by hand."
  # C++ libraries: each luaL_Reg table maps to a Lua global.
  for pair in card:Card effect:Effect group:Group duel:Duel debug:Debug; do
    lib="${pair%%:*}"; global="${pair##*:}"
    awk -v g="$global" -v lib="${lib}lib" '
      $0 ~ "luaL_Reg " lib "\\[\\]" {on=1; next}
      on && /^\};/ {on=0}
      on && match($0, /\{ *"[A-Za-z0-9_]+"/) { s=substr($0, RSTART, RLENGTH); gsub(/[{ "]/, "", s); print g "." s }
    ' "$core/lib$lib.cpp"
  done
  # Lua-side helpers.
  grep -hoE '^function (Auxiliary|Card|Duel|Group|Effect)\.[A-Za-z0-9_]+' "$scripts"/utility.lua "$scripts"/procedure.lua \
    | sed -E 's/^function //; s/^Auxiliary\./aux./'
  # Lua-side helper values scripts set, like aux.GCheckAdditional and aux.RCheckAdditional.
  grep -hoE '^Auxiliary\.[A-Za-z0-9_]+[[:space:]]*=' "$scripts"/utility.lua "$scripts"/procedure.lua \
    | sed -E 's/[[:space:]]*=$//; s/^Auxiliary\./aux./'
  # Constants.
  grep -hoE '^[A-Z][A-Z0-9_]+[[:space:]]*=' "$scripts"/constant.lua | sed -E 's/[[:space:]]*=$//; s/^/const./'
} | awk '!seen[$0]++' > "$out"
echo "wrote $(wc -l < "$out") lines to $out"
